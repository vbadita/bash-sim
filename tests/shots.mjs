// Take screenshots of a few typical sessions for visual review.
import { createRequire } from 'node:module';
import { serve } from './serve.mjs';
const { chromium } = createRequire(import.meta.url)('playwright');
const server = await serve(8977);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1000, height: 640 } });
page.on('pageerror', (e) => console.log('PAGEERROR', e));
await page.goto('http://127.0.0.1:8977/bash/');
await page.waitForTimeout(1500);
const run = async (c, wait = 600) => {
  await page.keyboard.type(c, { delay: 2 });
  await page.keyboard.press('Enter');
  await page.waitForTimeout(wait);
};
const shot = (n) => page.screenshot({ path: `tests/shot-${n}.png` });
await page.keyboard.press('Control+L');
await run('ll');
await run('ls -l /usr/bin | head -5');
await run('grep -n an data/fruits.txt');
await run('echo "a very long line that should wrap around the terminal because it is much longer than the width of the terminal window, isn\'t it, yes it is indeed"');
await shot(1);
await page.keyboard.press('Control+L');
await run('cal; free -h; df -h | head -3');
await run('tree projects');
await shot(2);
await run('vim scripts/hello.sh', 1000);
await shot(3);
await page.keyboard.type(':q');
await page.keyboard.press('Enter');
await page.waitForTimeout(300);
await run('sudo apt install -y neofetch figlet lolcat > /dev/null 2>&1; clear; neofetch', 6000);
await shot(4);
await page.keyboard.press('Control+L');
await run('figlet Hello | lolcat', 1500);
await page.keyboard.type('ls da');
await page.keyboard.press('Tab');
await page.keyboard.press('Enter');
await page.waitForTimeout(500);
await page.keyboard.type('ls ');
await page.keyboard.press('Tab');
await page.keyboard.press('Tab');
await page.waitForTimeout(500);
await shot(5);
await page.keyboard.press('Control+C');
await run('htop', 2000);
await shot(6);
await page.keyboard.press('q');
await page.waitForTimeout(300);
await browser.close();
server.close();
